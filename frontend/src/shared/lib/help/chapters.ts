export function chapterForPath(path: string): Chapter {
  let id = "start";
  if (path.startsWith("/help/")) id = path.split("/")[2];
  else if (path.startsWith("/settings/users")) id = "users";
  else if (path.startsWith("/settings") || path === "/audit") id = "settings";
  else if (path.includes("/receipt") || path === "/procurement") id = "receipt";
  else if (path.includes("/revision")) id = "revision";
  else if (path.startsWith("/production")) id = "planning";
  else if (path.startsWith("/processes")) id = "processes";
  else if (path.startsWith("/warehouse")) id = "warehouse";
  else if (
    path.startsWith("/operations") ||
    path.startsWith("/public/instructions")
  )
    id = "operations";
  else if (path.startsWith("/personnel")) id = "personnel";
  else if (path.startsWith("/repairs")) id = "repairs";
  else if (path.startsWith("/sales")) id = "sales";
  else if (path.startsWith("/finance") || path.startsWith("/analytics"))
    id = "finance";
  else if (path.startsWith("/profile") || path === "/login") id = "profile";
  return chapters.find((chapter) => chapter.id === id) ?? chapters[0];
}
